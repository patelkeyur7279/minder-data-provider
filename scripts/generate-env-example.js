#!/usr/bin/env node

/**
 * Generate .env.example from actual env() / process.env usages in src/.
 *
 * Why: "bring your own credentials" only works if developers know WHICH env
 * vars to set. Hand-maintained .env.example files drift from the code. This
 * script scans `src/` for `env('NAME')` (see `src/security/secrets.ts`) and
 * `process.env.NAME` usages, merges in any documented vars from the optional
 * `docs/providers/env-manifest.json`, and writes `.env.example` with safe
 * placeholders — never real values.
 *
 * No dependencies. Idempotent: re-running produces byte-identical output for
 * the same source tree (names are deduped and sorted).
 *
 * Usage: node scripts/generate-env-example.js [--src <dir>] [--out <file>] [--manifest <file>] [--check]
 *   --check   Exit non-zero if the existing output file would change (CI guard).
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '..');

// Reserved / framework-internal env vars that are not "bring your own
// credential" values — including them in .env.example would be noise at
// best and misleading at worst (e.g. NODE_ENV=your-name-here breaks tooling).
const DEFAULT_EXCLUDE = new Set(['NODE_ENV', 'NEXT_RUNTIME', '__NEXT_PROCESSED_ENV']);

const ENV_CALL_RE = /\benv\(\s*(['"])([A-Za-z_][A-Za-z0-9_]*)\1/g;
const PROCESS_ENV_RE = /\bprocess\.env\.([A-Za-z_][A-Za-z0-9_]*)\b/g;
const PROCESS_ENV_BRACKET_RE = /\bprocess\.env\[\s*(['"])([A-Za-z_][A-Za-z0-9_]*)\1\s*\]/g;

const SCANNABLE_EXT = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs']);

/**
 * Recursively list files under `dir`, skipping test files and common
 * non-source directories.
 */
function listSourceFiles(dir) {
  const results = [];
  if (!fs.existsSync(dir)) return results;

  const skipDirs = new Set(['node_modules', 'dist', '__tests__', '__mocks__']);

  const walk = (current) => {
    const entries = fs.readdirSync(current, { withFileTypes: true });
    for (const entry of entries) {
      if (entry.name.startsWith('.')) continue;
      const full = path.join(current, entry.name);

      if (entry.isDirectory()) {
        if (skipDirs.has(entry.name)) continue;
        walk(full);
        continue;
      }

      const ext = path.extname(entry.name);
      if (!SCANNABLE_EXT.has(ext)) continue;
      if (/\.(test|spec)\.[a-z]+$/i.test(entry.name)) continue;
      if (entry.name.endsWith('.d.ts')) continue;

      results.push(full);
    }
  };

  walk(dir);
  return results;
}

/**
 * Scan a single file's contents for env() / process.env.NAME usages.
 * Returns a Set of variable names found.
 */
function scanFileContents(contents) {
  const names = new Set();
  let match;

  ENV_CALL_RE.lastIndex = 0;
  while ((match = ENV_CALL_RE.exec(contents)) !== null) {
    names.add(match[2]);
  }

  PROCESS_ENV_RE.lastIndex = 0;
  while ((match = PROCESS_ENV_RE.exec(contents)) !== null) {
    names.add(match[1]);
  }

  PROCESS_ENV_BRACKET_RE.lastIndex = 0;
  while ((match = PROCESS_ENV_BRACKET_RE.exec(contents)) !== null) {
    names.add(match[2]);
  }

  return names;
}

/**
 * Scan `srcDir` for env var usages. Returns a Set of variable names.
 */
function scanSrcForEnvVars(srcDir) {
  const names = new Set();
  for (const file of listSourceFiles(srcDir)) {
    const contents = fs.readFileSync(file, 'utf8');
    for (const name of scanFileContents(contents)) {
      names.add(name);
    }
  }
  return names;
}

/**
 * Load the optional env manifest. Expected shape:
 *   { "NAME": { "description": "...", "required": true } | "description string" }
 * Returns a Map<name, { description }>. Returns an empty Map if the file is
 * absent or malformed (malformed is reported to stderr but never throws).
 */
function loadManifest(manifestPath) {
  const manifest = new Map();
  if (!manifestPath || !fs.existsSync(manifestPath)) return manifest;

  try {
    const raw = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    for (const [name, value] of Object.entries(raw)) {
      if (typeof value === 'string') {
        manifest.set(name, { description: value });
      } else if (value && typeof value === 'object') {
        manifest.set(name, { description: value.description || '', required: Boolean(value.required) });
      } else {
        manifest.set(name, { description: '' });
      }
    }
  } catch (err) {
    process.stderr.write(
      `[generate-env-example] Warning: could not parse ${manifestPath}: ${err.message}\n`
    );
  }

  return manifest;
}

/**
 * Build the final .env.example file content from a set of discovered names
 * and the (optional) manifest metadata.
 */
function buildEnvExampleContent(names, manifest) {
  const sorted = Array.from(names).sort((a, b) => a.localeCompare(b));

  const header = [
    '# .env.example',
    '#',
    '# Auto-generated by `npm run generate:env-example`. Do NOT edit by hand — your',
    '# changes will be overwritten. Instead, add/update entries in',
    '# `docs/providers/env-manifest.json` or the `env(\'NAME\')` / `process.env.NAME`',
    '# usages this file was scanned from.',
    '#',
    '# Copy this file to `.env` (or `.env.local`) and fill in real values.',
    '# NEVER commit `.env` — only this template.',
    '',
  ];

  if (sorted.length === 0) {
    header.push('# No env() / process.env usages were found in src/.');
    return header.join('\n') + '\n';
  }

  const lines = [...header];
  for (const name of sorted) {
    const meta = manifest.get(name);
    if (meta && meta.description) {
      lines.push(`# ${meta.description}${meta.required ? ' (required)' : ''}`);
    }
    lines.push(`${name}=your-${name.toLowerCase().replace(/_/g, '-')}-here`);
    lines.push('');
  }

  // Trim trailing blank line, keep exactly one newline at EOF.
  while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  return lines.join('\n') + '\n';
}

/**
 * Run the generator. Returns { content, names, outputPath, changed }.
 * Pure w.r.t. the filesystem except for the final write (skipped if `dryRun`).
 */
function main(options = {}) {
  const srcDir = options.srcDir || path.join(REPO_ROOT, 'src');
  const outPath = options.outPath || path.join(REPO_ROOT, '.env.example');
  const manifestPath =
    options.manifestPath || path.join(REPO_ROOT, 'docs', 'providers', 'env-manifest.json');
  const exclude = options.exclude || DEFAULT_EXCLUDE;
  const dryRun = Boolean(options.dryRun);

  const scanned = scanSrcForEnvVars(srcDir);
  const manifest = loadManifest(manifestPath);

  const names = new Set();
  for (const name of scanned) {
    if (!exclude.has(name)) names.add(name);
  }
  for (const name of manifest.keys()) {
    if (!exclude.has(name)) names.add(name);
  }

  const content = buildEnvExampleContent(names, manifest);
  const previous = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
  const changed = previous !== content;

  if (!dryRun) {
    fs.writeFileSync(outPath, content, 'utf8');
  }

  return { content, names: Array.from(names).sort(), outputPath: outPath, changed };
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const options = {};
  const checkOnly = args.includes('--check');

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--src') options.srcDir = path.resolve(args[++i]);
    else if (args[i] === '--out') options.outPath = path.resolve(args[++i]);
    else if (args[i] === '--manifest') options.manifestPath = path.resolve(args[++i]);
  }

  if (checkOnly) options.dryRun = true;

  const result = main(options);

  if (checkOnly) {
    if (result.changed) {
      process.stderr.write(
        `[generate-env-example] ${path.relative(REPO_ROOT, result.outputPath)} is out of date. ` +
          `Run \`npm run generate:env-example\`.\n`
      );
      process.exit(1);
    }
    process.stdout.write(`[generate-env-example] ${path.relative(REPO_ROOT, result.outputPath)} is up to date.\n`);
    process.exit(0);
  }

  process.stdout.write(
    `[generate-env-example] Wrote ${path.relative(REPO_ROOT, result.outputPath)} with ${result.names.length} variable(s): ${result.names.join(', ') || '(none)'}\n`
  );
}

module.exports = {
  main,
  scanSrcForEnvVars,
  scanFileContents,
  loadManifest,
  buildEnvExampleContent,
  listSourceFiles,
  DEFAULT_EXCLUDE,
};
